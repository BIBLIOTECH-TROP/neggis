function formatTime(seconds) {
  if (!Number.isFinite(seconds)) return '0:00';
  const min = Math.floor(seconds / 60);
  const sec = Math.floor(seconds % 60).toString().padStart(2, '0');
  return `${min}:${sec}`;
}

function renderPlaylist() {
  playlist.innerHTML = '';
  tracks.forEach((track, i) => {
    const item = document.createElement('button');
    item.type = 'button';
    item.className = `track ${i === current ? 'active' : ''}`;
    item.innerHTML = `<span class="num">${String(i + 1).padStart(2, '0')}</span><img src="${track.photo}" alt=""><span><strong>${track.title}</strong><small>${track.artist}</small></span><span>♡</span>`;
    item.addEventListener('click', () => loadTrack(i, true));
    playlist.appendChild(item);
  });
}

function renderLyrics() {
  const track = tracks[current];
  lyrics.innerHTML = '';

  track.lyrics.forEach((line) => {
    // Aceita os dois formatos:
    // [tempo, "texto"]
    // { time: tempo, text: "texto" }

    const time = Array.isArray(line) ? line[0] : line.time;
    const text = Array.isArray(line) ? line[1] : line.text;

    const el = document.createElement('button');

    el.type = 'button';
    el.className = 'lyric-line';

    el.dataset.time = time;
    el.textContent = text;

    el.addEventListener('click', () => {
      audio.currentTime = time;

      if (audio.paused) {
        audio.play().catch(() => {});
      }
    });

    lyrics.appendChild(el);
  });

  lyricStatus.textContent = track.approx
    ? 'sincronização aproximada'
    : 'sincronização por tempo';

  updateLyrics();
}

function updateLyrics() {
  const lines = [...lyrics.querySelectorAll('.lyric-line')];
  if (!lines.length) return;
  let active = -1;
  const now = audio.currentTime;
  lines.forEach((line, i) => { if (now >= Number(line.dataset.time)) active = i; line.classList.remove('active','past'); });
  lines.forEach((line, i) => {
    if (i < active) line.classList.add('past');
    if (i === active) line.classList.add('active');
  });
  const target = lines[active];
  if (target && !document.hidden) target.scrollIntoView({behavior:'smooth',block:'center'});
}

function loadTrack(index, autoplay = false) {
  current = (index + tracks.length) % tracks.length;
  const track = tracks[current];
  photo.parentElement.classList.add('changing');
  setTimeout(() => {
    photo.src = track.photo;
    bg.style.backgroundImage = `url("${track.photo}")`;
    title.textContent = track.title;
    artist.textContent = track.artist;
    trackNumber.textContent = `FAIXA ${String(current + 1).padStart(2, '0')}`;
    audio.src = track.audio;
    audio.load();
    photo.parentElement.classList.remove('changing');
    renderPlaylist();
    renderLyrics();
    if (autoplay) audio.play().catch(() => {});
  }, 180);
}

